import assert from 'node:assert/strict';
import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { tmpdir } from 'node:os';

// 使用独立数据目录验收，不修改用户的项目、会话或凭据。
const root = await mkdtemp(path.join(tmpdir(), 'jinggong-free-session-'));
const data = path.join(root, 'data');
const checks = [];
const env = { ...process.env, JINGGONG_TEST_DATA: data };
delete env.ELECTRON_RUN_AS_NODE;
let app;
try {
  app = await electron.launch({ ...(process.env.JINGGONG_TEST_EXE ? { executablePath: process.env.JINGGONG_TEST_EXE, args: [] } : { args: ['.'] }), env });
  const page = await app.firstWindow();
  await expect(page.locator('.runtime-summary')).toBeVisible({ timeout: 30000 });
  await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => { throw new Error('创建空工作区不应弹出 Git 目录选择'); }; });
  await page.getByRole('button', { name: '新建工作区', exact: true }).click();
  await page.getByRole('textbox', { name: '工作区名称', exact: true }).fill('日常工作');
  await page.getByRole('button', { name: '创建工作区', exact: true }).click();
  const group = page.getByRole('region', { name: '工作区 日常工作', exact: true });
  await expect(group).toBeVisible();
  const workspaces = await page.evaluate(() => window.jinggong.listWorkspaces());
  assert.equal(workspaces.length, 1);
  assert.equal(workspaces[0].repositories.length, 0);
  checks.push('可创建没有 Git 仓库的工作区，不弹目录选择');
  await page.getByRole('button', { name: '在工作区 日常工作 新建会话', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('新建会话工作区', { exact: true })).toHaveValue(workspaces[0].id);
  await expect(dialog.getByLabel('新建会话项目', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('新建会话 Runtime', { exact: true })).toHaveValue('claude_agent_sdk');
  await dialog.getByRole('button', { name: '创建会话', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '输入任务' })).toBeVisible();
  let sessions = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  const workspaceSession = sessions[0];
  assert.equal(workspaceSession.workspaceId, workspaces[0].id);
  assert.equal(workspaceSession.projectId, undefined);
  assert.equal(workspaceSession.runtimeKind, 'claude_agent_sdk');
  await expect(group.locator('.session-row')).toHaveCount(1);
  checks.push('工作区可直接新建不关联项目的会话，并显示在该工作区下');
  await page.keyboard.press('Control+n');
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('新建会话工作区', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('新建会话项目', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('新建会话 Runtime', { exact: true })).toHaveValue('claude_agent_sdk');
  await dialog.getByLabel('新建会话 Runtime', { exact: true }).selectOption('jinggong');
  await dialog.getByRole('button', { name: '创建会话', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  sessions = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  const standalone = sessions.find(item => item.id !== workspaceSession.id);
  assert.ok(standalone);
  assert.equal(standalone.projectId, undefined);
  assert.equal(standalone.workspaceId, undefined);
  assert.equal(standalone.mode, 'read');
  assert.equal(standalone.runtimeKind, 'jinggong');
  await expect(page.getByLabel('当前会话运行时', { exact: true })).toHaveValue('jinggong');
  await page.getByLabel('当前会话运行时', { exact: true }).selectOption('codex');
  await page.waitForFunction(async id => (await window.jinggong.bootstrap()).sessions.find(item => item.id === id)?.runtimeKind === 'codex', standalone.id);
  const switched = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  assert.equal(switched.find(item => item.id === workspaceSession.id)?.runtimeKind, 'claude_agent_sdk');
  checks.push('无中转站配置时也可在模型旁切换当前会话 Runtime，其他会话的引擎保持独立');
  await expect(page.getByRole('region', { name: '独立会话', exact: true }).locator('.session-row')).toHaveCount(1);
  checks.push('Ctrl+N 默认新建独立会话，可不关联工作区和项目');
  const repo = path.join(root, '测试项目');
  await mkdir(repo);
  const git = args => execFileSync('git', args, { cwd: repo, windowsHide: true, encoding: 'utf8' });
  git(['init', '-b', 'main']);
  await writeFile(path.join(repo, 'README.md'), '# 隔离会话测试项目\n');
  git(['add', '.']);
  git(['-c', 'user.name=精工测试', '-c', 'user.email=test@example.invalid', 'commit', '-m', '创建会话验收项目']);
  await app.evaluate(({ dialog }, repo) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [repo] }); }, repo);
  await page.getByRole('button', { name: '添加项目目录', exact: true }).click();
  await expect(page.locator('.project-item')).toBeVisible();
  await page.keyboard.press('Control+n');
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('新建会话工作区', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('新建会话项目', { exact: true })).toHaveValue('');
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  checks.push('当前选中项目时 Ctrl+N 仍默认独立，且取消不创建会话');
  const topNavigation = page.locator('.top-nav');
  await expect(topNavigation.getByRole('button', { name: '新建会话', exact: true })).toBeVisible();
  await expect(topNavigation.getByText('Agent 工作台', { exact: true })).toHaveCount(0);
  const sessionsBeforeTopNavigation = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  await topNavigation.getByRole('button', { name: '新建会话', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.getByLabel('新建会话工作区', { exact: true })).toHaveValue('');
  await expect(dialog.getByLabel('新建会话项目', { exact: true })).toHaveValue('');
  await dialog.getByRole('button', { name: '创建会话', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('textbox', { name: '输入任务' })).toBeVisible();
  sessions = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  assert.equal(sessions.length, sessionsBeforeTopNavigation.length + 1);
  const topNavigationSession = sessions.find(item => !sessionsBeforeTopNavigation.some(previous => previous.id === item.id));
  assert.ok(topNavigationSession);
  assert.equal(topNavigationSession.projectId, undefined);
  assert.equal(topNavigationSession.workspaceId, undefined);
  assert.equal(topNavigationSession.mode, 'read');
  assert.equal(topNavigationSession.runtimeKind, 'claude_agent_sdk');
  checks.push('左上角 Agent 工作台替换为新建会话按钮，真实点击可创建不关联工作区或项目的独立会话');
  await page.getByRole('button', { name: '全局设置', exact: true }).click();
  await page.getByRole('button', { name: '运行时', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Runtime 组件状态', exact: true })).toBeVisible();
  await expect(page.locator('input[name="runtime-kind"]')).toHaveCount(0);
  await expect(page.getByText('Claude Console API Key', { exact: true })).toHaveCount(0);
  await expect(page.locator('input[id*="claude"], select[id*="claude"]')).toHaveCount(0);
  await page.getByRole('button', { name: '会话与数据', exact: true }).click();
  await expect(page.getByRole('button', { name: '导出所选会话', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '导入会话或记忆', exact: true })).toBeVisible();
  await expect(page.getByLabel('选择会话接收项目', { exact: true })).toHaveValue('');
  checks.push('Claude 无独立模型/Key 表单；会话导入导出集中在设置，可选独立导入');
  await page.keyboard.press('Control+n');
  await expect(page.getByRole('dialog').getByLabel('新建会话工作区', { exact: true })).toHaveValue('');
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('button', { name: '导出所选会话', exact: true })).toHaveCount(0);
  await expect(page.locator('.brand strong')).toHaveText('精工Agent');
  const brand = await page.locator('.brand strong').evaluate(element => ({ height: element.getBoundingClientRect().height, lineHeight: parseFloat(getComputedStyle(element).lineHeight), fits: element.scrollWidth <= element.clientWidth }));
  assert.ok(brand.fits && brand.height < brand.lineHeight * 1.6, JSON.stringify(brand));
  await page.reload();
  await expect(page.locator('.runtime-summary')).toBeVisible({ timeout: 30000 });
  sessions = (await page.evaluate(() => window.jinggong.bootstrap())).sessions;
  assert.equal(sessions.find(item => item.id === workspaceSession.id)?.workspaceId, workspaces[0].id);
  assert.equal(sessions.find(item => item.id === standalone.id)?.workspaceId, undefined);
  assert.equal(sessions.find(item => item.id === topNavigationSession.id)?.workspaceId, undefined);
  assert.equal(sessions.find(item => item.id === workspaceSession.id)?.runtimeKind, 'claude_agent_sdk');
  assert.equal(sessions.find(item => item.id === standalone.id)?.runtimeKind, 'codex');
  assert.equal(sessions.find(item => item.id === topNavigationSession.id)?.runtimeKind, 'claude_agent_sdk');
  checks.push('品牌名称单行完整显示；重载后工作区和独立会话归属保持');
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/workspace-session-smoke.png' });
  const report = { date: new Date().toISOString(), passed: true, checks, executable: process.env.JINGGONG_TEST_EXE || '开发 Electron', testData: root };
  await writeFile('test-results/workspace-session-smoke.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  if (app) await app.close();
}
