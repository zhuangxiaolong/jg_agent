async function chromiumPath() {
  if (process.env.PLAYWRIGHT_CHROMIUM_PATH) return process.env.PLAYWRIGHT_CHROMIUM_PATH;
  const root = path.join(process.env.LOCALAPPDATA || '', 'ms-playwright');
  if (!existsSync(root)) return undefined;
  const folders = (await readdir(root)).filter(name => /^chromium-\d+$/.test(name)).sort((a, b) => Number(b.slice(9)) - Number(a.slice(9)));
  for (const folder of folders) for (const relative of ['chrome-win64/chrome.exe', 'chrome-win/chrome.exe']) {
    const candidate = path.join(root, folder, relative);
    if (existsSync(candidate)) return candidate;
  }
}
